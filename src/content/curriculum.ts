/**
 * The curriculum map: ten stages, each made of modules with prerequisites.
 *
 * Stage 1 is fully written. Later stages are listed honestly as "planned":
 * their module titles, intended lessons and unlock rules are real, but the
 * lessons themselves are not written yet and the app says so.
 */
import type { Block, Module, Stage, Text } from './schema';
import { p, t } from './authoring';

function planned(
  id: string,
  stageId: string,
  title: [string, string],
  description: [string, string],
  prerequisites: string[],
  plannedLessons: Array<[string, string]>,
): Module {
  return {
    id,
    stageId,
    title: t(title[0], title[1]),
    description: t(description[0], description[1]),
    prerequisites,
    status: 'planned',
    lessonIds: [],
    plannedLessons: plannedLessons.map(([en, he]) => t(en, he)),
  };
}

