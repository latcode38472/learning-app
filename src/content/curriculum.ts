function stage(
  id: string,
  number: number,
  title: [string, string],
  summary: [string, string],
  description: Block[],
  status: Stage['status'],
  moduleIds: string[],
  unlockNote: [string, string],
  compute: Stage['compute'],
): Stage {
  return {
    id,
    number,
    title: t(title[0], title[1]),
    summary: t(summary[0], summary[1]),
    description,
    status,
    moduleIds,
    unlockNote: t(unlockNote[0], unlockNote[1]),
    compute,
  };
}

